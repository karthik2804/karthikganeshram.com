import { readFileSync, writeFileSync } from "node:fs";

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error("Usage: node scripts/generate-world-map.mjs <land.geojson> <output.html>");
  process.exit(1);
}

const data = JSON.parse(readFileSync(input, "utf8"));
const project = ([longitude, latitude]) => [
  Math.round(((longitude + 180) / 360) * 1000),
  Math.round(((90 - latitude) / 180) * 500),
];
const polygonPath = (rings) => rings.map((ring) => {
  const points = ring.map(project).filter((point, index, all) =>
    index === 0 || point[0] !== all[index - 1][0] || point[1] !== all[index - 1][1]
  );
  return `M${points.map(([x, y]) => `${x} ${y}`).join(" ")}Z`;
}).join("");

const paths = data.features.flatMap(({ geometry }) => {
  if (geometry.type === "Polygon") return [polygonPath(geometry.coordinates)];
  if (geometry.type === "MultiPolygon") return geometry.coordinates.map(polygonPath);
  return [];
});

const source = "Natural Earth ne_110m_land, public domain";
writeFileSync(output, `<!-- ${source}; generated by scripts/generate-world-map.mjs -->\n<path d="${paths.join("")}" />\n`);
